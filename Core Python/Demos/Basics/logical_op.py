#1) and : if both operands are true then return true otherwise return false
print(True and True)
print(True and False)
print(False and True)
print(False and False)

#2) or : if both operands are false then return false otherwise return true
print(True and True)
print(True and False)
print(False and True)
print(False and False)

#3) not : opposite to operands
print(not True)
print(not False)
